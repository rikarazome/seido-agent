PROGRAM_ENTRY = """
- id: {pid}
  name: {name}
  layer: {layer}
  municipality: {municipality}
  subject: {subject}
  unit: {unit}
  amount_type: {amount_type}
  potential_amount: {potential_amount}
  status: supported
  statute:
    - {{ ref: "{ref}", url: "{url}" }}
"""


def main():
    existing = {p["id"] for p in
                yaml.safe_load(PROGRAMS.read_text(encoding="utf-8"))}
    total_gen = 0
    total_appended = 0

    # Batch ward programs
    for gen_func, name_template, ref_template in [
        (gen_kindergarten, "私立幼稚園等補助金（{ward}）",
         "{ward} shiritsu youchien hojo"),
        (gen_daycare_subsidy, "認可外保育施設利用者補助（{ward}）",
         "{ward} ninkagai hoiku hojo"),
    ]:
        for pid, ward, yen, rule_tmpl, cases_tmpl, statute_tmpl, subject, unit, amt_type in gen_func():
            rule_dir = REPO / "rules" / "municipal" / ward
            golden_dir = REPO / "tests" / "golden" / pid
            rule_dir.mkdir(parents=True, exist_ok=True)
            golden_dir.mkdir(parents=True, exist_ok=True)

            _write(rule_dir / f"{pid}.pl",
                   rule_tmpl.format(pid=pid, ward=ward, yen=yen))
            _write(golden_dir / "cases.yaml",
                   cases_tmpl.format(ward=ward, yen=yen))
            _write(golden_dir / "statute_source.md",
                   statute_tmpl.format(ward=ward, yen=yen))
            total_gen += 1

            if pid not in existing:
                url = f"https://www.city.{ward}.tokyo.jp/"  # ward top page
                if ward == "chiyoda":
                    url = f"https://www.city.{ward}.lg.jp/"
                elif ward in ("katsushika", "suginami"):
                    url = f"https://www.city.{ward}.lg.jp/"
                with PROGRAMS.open("a", encoding="utf-8", newline="\n") as f:
                    f.write(PROGRAM_ENTRY.format(
                        pid=pid,
                        name=name_template.format(ward=ward),
                        layer="municipal", municipality=ward,
                        subject=subject, unit=unit, amount_type=amt_type,
                        potential_amount=yen,
                        ref=ref_template.format(ward=ward), url=url))
                total_appended += 1

    # National programs
    for p in gen_national_extra():
        pid = p["pid"]
        rule_dir = REPO / "rules" / "national"
        golden_dir = REPO / "tests" / "golden" / pid
        rule_dir.mkdir(parents=True, exist_ok=True)
        golden_dir.mkdir(parents=True, exist_ok=True)

        _write(rule_dir / f"{pid}.pl", p["rule"])
        _write(golden_dir / "cases.yaml", p["cases"])
        _write(golden_dir / "statute_source.md",
               f"# {p['name']} -- source fixation\n**VERIFIED (2026-06-15)**\n"
               f"Source: {p['ref']} {p['url']}\n")
        total_gen += 1

        if pid not in existing:
            with PROGRAMS.open("a", encoding="utf-8", newline="\n") as f:
                f.write(PROGRAM_ENTRY.format(
                    pid=pid, name=p["name"], layer=p["layer"],
                    municipality="null", subject=p["subject"],
                    unit=p["unit"], amount_type=p["amount_type"],
                    potential_amount=p["potential_amount"],
                    ref=p["ref"], url=p["url"]))
            total_appended += 1

    print(f"Generated {total_gen} programs; appended {total_appended} to programs.yaml")


if __name__ == "__main__":
    main()
