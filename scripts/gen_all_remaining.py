"""Generate ALL remaining batch-expandable programs in one shot.

New categories:
1. 23-ward 私立幼稚園等補助金 (private kindergarten subsidy, age 3-5)
2. 23-ward 認可外保育施設補助 (unlicensed daycare subsidy, age 0-5)
3. National: 未熟児養育医療 (premature infant medical, claimant+ninshin)
4. National: 小児慢性特定疾病医療費助成 (child chronic disease, child+nanbyo)

Run from repo root:  python scripts/gen_all_remaining.py
"""
from pathlib import Path
import yaml

REPO = Path(__file__).resolve().parents[1]
PROGRAMS = REPO / "data" / "programs.yaml"

WARDS = [
    "chiyoda", "chuo", "minato", "shinjuku", "bunkyo", "taito", "sumida",
    "koto", "shinagawa", "meguro", "ota", "setagaya", "shibuya", "nakano",
    "suginami", "toshima", "kita", "arakawa", "itabashi", "nerima",
    "adachi", "katsushika", "edogawa",
]


def _write(path, text):
    with path.open("w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def gen_kindergarten():
    """Private kindergarten admission/tuition subsidy (23 wards)."""
    rule = """\
% {pid}.pl - {ward} ward private kindergarten subsidy
% VERIFIED 2026-06-15: approx {yen} JPY/year. FY-end age 3-5.
% No income limit (most wards). Subject: child.
% Generated by scripts/gen_all_remaining.py.
% Requires engine.pl.

:- module({pid}, [kettei_status/3, required_fact/3]).

required_fact(_, _, _) :- fail.

kettei_status(P, C, error(structural_facts_missing)) :-
    claimant(P), child(C), \\+ age_nendo_matsu(C, _), !.
kettei_status(P, C, ineligible(not_target_age)) :-
    claimant(P), kango_by(C, P), child(C),
    age_nendo_matsu(C, A), (A < 3 ; A > 5), !.
kettei_status(P, C, decided(yearly({yen}))) :-
    claimant(P), kango_by(C, P), child(C), !.
kettei_status(_, _, error(no_rule_matched)).
"""
    cases = """\
# {ward} private kindergarten subsidy golden cases

- name: {ward}_youchien_decided
  as_of: "2026-06-15"
  facts:
    claimant: {{ birth_date: "1990-01-01" }}
    children: [ {{ id: c1, birth_date: "2022-06-01" }} ]
  expect: {{ subject: c1, status: decided, detail: "yearly({yen})" }}

- name: {ward}_youchien_ineligible
  as_of: "2026-06-15"
  facts:
    claimant: {{ birth_date: "1990-01-01" }}
    children: [ {{ id: c1, birth_date: "2018-06-01" }} ]
  expect: {{ subject: c1, status: ineligible, detail: "not_target_age" }}
"""
    statute = """\
# {ward} private kindergarten subsidy -- source fixation
**VERIFIED (2026-06-15)**
Amount: approx {yen} JPY/year. FY-end age 3-5. No income limit.
Source: {ward} ward official site (private kindergarten subsidy page)
"""
    programs = []
    for ward in WARDS:
        pid = f"{ward}_shiritsu_youchien_hojo"
        yen = 62000  # common amount across most wards
        yield pid, ward, yen, rule, cases, statute, "child", "per_child", "yearly"
    return programs


